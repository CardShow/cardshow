#!/usr/bin/env node
// Loads TitoCollects' Nov 7 import package into one dealer account, as SQL.
// Golden fixture for the Show Home report (CLAUDE.md "Trades + Show Home").
//
//   node scripts/load_fixture_tito_nov7.js --dir <folder with the CSVs> --owner <auth uuid> \
//        [--handle tito_test] [--show <CardShow show id>] > fixture.sql
//   psql -d <db> -f fixture.sql            (or paste into the Supabase SQL editor)
//
// Files read from --dir: cardshow_inventory_import.csv, cardshow_transactions_nov7.csv,
// cardshow_transaction_items_nov7.csv (from the import package in Drive; not in the repo,
// since they're a real dealer's inventory and costs).
//
// Without --show the show is a dealer-private "Mall Show" (dealer_shows) and every
// transaction goes in dealer_transactions. With --show <id>, cash sales and the lot sale
// go on the ledger (show_floor_transactions, source 'import') against that CardShow show,
// so organizer GMV can be checked; trades still go in dealer_transactions.
// Ids are derived from the owner + row, so loading twice changes nothing.
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const args = {};
for (let i = 2; i < process.argv.length; i += 2) args[process.argv[i].replace(/^--/, '')] = process.argv[i + 1];
if (!args.dir || !args.owner) { console.error('usage: --dir <folder> --owner <uuid> [--handle h] [--show id]'); process.exit(1); }
const OWNER = args.owner;
const HANDLE = args.handle || 'tito_test';
const SHOW = args.show || null;

function parseCsv(text) {
  const rows = []; let row = [], cur = '', q = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (q) {
      if (c === '"' && text[i + 1] === '"') { cur += '"'; i++; }
      else if (c === '"') q = false;
      else cur += c;
    } else if (c === '"') q = true;
    else if (c === ',') { row.push(cur); cur = ''; }
    else if (c === '\n' || c === '\r') {
      if (c === '\r' && text[i + 1] === '\n') i++;
      row.push(cur); cur = '';
      if (row.some(v => v !== '')) rows.push(row);
      row = [];
    } else cur += c;
  }
  if (cur !== '' || row.length) { row.push(cur); if (row.some(v => v !== '')) rows.push(row); }
  const head = rows.shift().map(h => h.trim());
  return rows.map(r => Object.fromEntries(head.map((h, i) => [h, (r[i] ?? '').trim()])));
}
const read = f => parseCsv(fs.readFileSync(path.join(args.dir, f), 'utf8').replace(/^﻿/, ''));
const inventory = read('cardshow_inventory_import.csv');
const txns = read('cardshow_transactions_nov7.csv');
const items = read('cardshow_transaction_items_nov7.csv');

// Stable uuid from text (md5, formatted as a v4-shaped uuid).
function uid(s) {
  const h = crypto.createHash('md5').update(OWNER + '|' + s).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}
const q = v => (v === null || v === undefined || v === '') ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const num = v => { const n = parseFloat(String(v ?? '').replace(/[^0-9.\-]/g, '')); return isNaN(n) ? 'null' : String(n); };
const num0 = v => (num(v) === 'null' ? '0' : num(v));
const int = v => { const m = String(v ?? '').match(/\d{4}|\d+/); return m ? m[0] : 'null'; };
const invId = code => uid('inv:' + code);
const DATE = '2026-11-07';
const AT = d => `'${DATE}T12:00:00Z'::timestamptz + interval '${d} minutes'`;

const TYPE = { LOT_SALE: 'lot_sale', SALE: 'sale', TRADE: 'trade', TRADE_UNGROUPED: 'trade', BUY: 'buy' };
const BASIS = { observed: 'observed', allocated: 'allocated', agreed_trade_value: 'agreed_trade_value', unknown: 'unknown' };
const invByCode = Object.fromEntries(inventory.map(r => [r.Code, r]));

const out = [];
out.push('-- Generated by scripts/load_fixture_tito_nov7.js. Re-runnable.');
out.push('begin;');
out.push(`insert into public.sellers (id, handle) values (${q(OWNER)}, ${q(HANDLE)}) on conflict do nothing;`);

let dealerShow = null;
if (!SHOW) {
  dealerShow = uid('dealer_show:mall-2026-11-07');
  out.push(`insert into public.dealer_shows (id, owner_id, name, show_date, venue) values (${q(dealerShow)}, ${q(OWNER)}, 'Mall Show', '${DATE}', 'Mall') on conflict (id) do nothing;`);
}
const showCols = SHOW ? `show_id` : `dealer_show_id`;
const showVal = SHOW ? q(SHOW) : q(dealerShow);

// Inventory (181 cards) + costs.
for (const r of inventory) {
  const grade = /^\d+(\.\d+)?$/.test(r.Grade) ? r.Grade : '';
  out.push(`insert into public.inventory (id, seller_id, card_title, player, year, card_set, card_number, parallel, grader, grade, cert_number, condition, price, status, stock_code, sold_price, item_type)
  values (${q(invId(r.Code))}, ${q(OWNER)}, ${q(r['Card Title'])}, ${q(r.Player)}, ${int(r.Year)}, ${q(r.Set)}, ${q(r.Number)}, ${q(r['Parallel/Variant'])}, ${q(r.Grader)}, ${num(grade)}, ${q(r['Cert #'])}, ${q(r.Condition)}, ${num(r.Price)}, ${q(r.Status || 'Available')}, ${q(r.Code)}, ${num(r['Sold For'])}, 'card')
  on conflict (id) do nothing;`);
  // Blank cost = unknown, except Single 78: blank in Master, $0 in Show In vs Out (spec 1.3).
  const cost = r.Code === 'R-78' && r.Cost === '' ? '0' : r.Cost;
  if (cost !== '') {
    out.push(`insert into public.inventory_costs (inventory_id, owner_id, cost_basis, acquired_at, notes)
  values (${q(invId(r.Code))}, ${q(OWNER)}, ${num(cost)}, ${q(r['Acquired Date'])}, ${q(r.Notes)}) on conflict (inventory_id) do nothing;`);
  }
}

// Transactions.
const ledgerKey = {};   // txn id → ledger sale_key (when on the ledger)
txns.forEach((t, n) => {
  const type = TYPE[t.Type];
  if (!type) throw new Error('Unknown type ' + t.Type + ' on ' + t['Transaction ID']);
  const id = uid('txn:' + t['Transaction ID']);
  const onLedger = SHOW && (type === 'sale' || type === 'lot_sale');
  if (onLedger) {
    const outs = items.filter(i => i['Transaction ID'] === t['Transaction ID'] && i.Direction === 'out');
    const card = type === 'sale' ? invByCode[outs[0].Code] : null;
    ledgerKey[t['Transaction ID']] = id;
    out.push(`insert into public.show_floor_transactions (id, client_sale_id, sold_at, sold_price, payment_method, source, txn_type, inventory_id, card_title, player, seller_id, seller_handle, show_id, is_test, api_eligible, item_type)
  select ${q(id)}, ${q(id)}, ${AT(n)}, ${num0(t['Cash In'])}, ${q(t['Payment Method'] || 'Cash')}, 'import', ${q(type)}, ${card ? q(invId(card.Code)) : 'null'}, ${q(card ? card['Card Title'] : `Lot · ${outs.length} cards`)}, ${q(card ? card.Player : null)}, ${q(OWNER)}, ${q(HANDLE)}, ${q(SHOW)}, true, ${type === 'sale'}, ${type === 'lot_sale' ? "'lot'" : "'card'"}
  where not exists (select 1 from public.show_floor_transactions where id = ${q(id)});`);
  } else {
    out.push(`insert into public.dealer_transactions (id, owner_id, ${showCols}, txn_type, occurred_at, cash_in, cash_out, payment_method, is_ungrouped, source, import_key, review_note)
  values (${q(id)}, ${q(OWNER)}, ${showVal}, ${q(type)}, ${AT(n)}, ${num0(t['Cash In'])}, ${num0(t['Cash Out'])}, ${q(t['Payment Method'])}, ${t.Type === 'TRADE_UNGROUPED'}, 'import', ${q(t['Transaction ID'])}, ${q(t['Review Note'])})
  on conflict (id) do nothing;`);
  }
});

// Items + per-card costs. One-card ledger sales get their item from the ledger trigger.
for (const it of items) {
  const tid = it['Transaction ID'];
  const t = txns.find(x => x['Transaction ID'] === tid);
  const type = TYPE[t.Type];
  const id = uid(`item:${tid}:${it.Direction}:${it.Code}`);
  const dtx = uid('txn:' + tid);
  const ledger = ledgerKey[tid];
  if (ledger && type === 'sale') {
    out.push(`insert into public.transaction_item_costs (transaction_item_id, owner_id, cost_at_sale)
  select i.id, ${q(OWNER)}, ${num(it['Cost Basis'])} from public.transaction_items i where i.sale_key = ${q(ledger)} and i.direction = 'out'
  on conflict (transaction_item_id) do nothing;`);
    continue;
  }
  const basis = BASIS[it['Price Basis']] || 'unknown';
  out.push(`insert into public.transaction_items (id, sale_key, transaction_id, dealer_txn_id, owner_id, inventory_id, card_title, card_ref, price, price_basis, identification_status, direction)
  values (${q(id)}, ${q(ledger || dtx)}, ${ledger ? q(ledger) : 'null'}, ${ledger ? 'null' : q(dtx)}, ${q(OWNER)}, ${q(invId(it.Code))}, ${q(it.Card)}, jsonb_build_object('stock_code', ${q(it.Code)}), ${num(it.Value)}, ${q(basis)}, 'confirmed', ${q(it.Direction)})
  on conflict (id) do nothing;`);
  if (it.Direction === 'out') {
    out.push(`insert into public.transaction_item_costs (transaction_item_id, owner_id, cost_at_sale)
  values (${q(id)}, ${q(OWNER)}, ${num(it['Cost Basis'])}) on conflict (transaction_item_id) do nothing;`);
  } else if (!ledger) {
    out.push(`update public.inventory_costs set acquired_txn_id = ${q(dtx)} where inventory_id = ${q(invId(it.Code))} and acquired_txn_id is null;`);
  }
}
out.push('commit;');
process.stdout.write(out.join('\n') + '\n');
